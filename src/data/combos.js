/** Convierte un combo/pack en un producto agregable al carrito. */
export function comboToCartProduct(combo) {
  return {
    id: combo.id,
    name: combo.title,
    category: 'Packs',
    description: combo.description,
    price: combo.promoPrice,
    unit: 'pack',
    emoji: combo.emoji,
    badge: combo.badge,
    gradientFrom: combo.gradientFrom,
    gradientTo: combo.gradientTo,
  };
}
